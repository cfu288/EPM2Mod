"""Twelve film slots: every visible art filter (NOTES §33). Generates slots/cave12.s, assembles it, and writes
  patches/slots12-code.json     structure (replaces slot3-code / slots7-code)
  patches/slots12-neutral.json  stock Natural settings in the nine slots that hold no film yet
  patches/film-pro400h-pa2-s12.json  the Pro 400H patch reduced to its three stills tables
Slots: Cross Process I, Light Tone (stock three-record handlers), Pop Art I (gamma3), and nine generic ones:
Pale&Light I, Soft Focus, Pin Hole I, Diorama under their own filter numbers; Grainy Film, Gentle Sepia, Dramatic
Tone, Key Line, Watercolor through the numbers of hidden second types (102, 106, 108, 145, 167), which
art_GetFilterType is made to return for those menu entries.      python3 -I build_slots12.py"""
import json, os, struct, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..", "..", "..")
BIN = os.path.expanduser("~/opt/mn10300/bin/mn10300-elf-"); B = 0x7E421020
b0 = open(os.path.join(ROOT, "build/blocks/OLY_E_101_1600_0000_0000.BIN.block0.bin"), "rb").read()
u32 = lambda a: struct.unpack_from("<I", b0, a - B)[0]
def op(addr, new): return {"type": "bytes", "block": 0, "offset": hex(addr - B), "expect": b0[addr - B:addr - B + len(new)].hex(), "new": bytes(new).hex()}
CAVE1, CAVE2, CAVE2_LEN, RUN3 = 0x7E880F5C, 0x7ECB0888, 1912, 0x7F033B7C
DEF = [0x7E74E7BC, 0x7E74E9BC, 0x7E7517BC, 0x7E7519BC, 0x7E7547BC, 0x7E7549BC, 0x7E7577BC, 0x7E7579BC]
PRO_RECS = (0x7E78B3DC, 0x7E78B3FC, 0x7E78B47C)                       # Pro 400H: records of Pale&Light, Light Tone, Pop Art II
pro_tabs = [struct.unpack_from("<8I", b0, r - B) for r in PRO_RECS]
FREED = [t for rec in pro_tabs for i, t in enumerate(rec) if i != 1]   # 21 tables Pro 400H gives up (it keeps index 1 of each record)
POOL = [RUN3, RUN3 + 512, 0x7E75E4F0, 0x7E75E8F0, 0x7E75ECF0, 0x7E75F0F0, 0x7E75FAF0, 0x7E75F8F0, 0x7E7616F0, 0x7E75FCF0, 0x7E75FEF0] + FREED
# name: codes (still, movie), saturation pair, six-axis records, menu entry (stored picture mode) or None
SLOTS = [("palelight1", (71, 80), 0x7E7696A4, (0x7E76949E, 0x7E7694AA), None), ("softfocus", (69, 78), 0x7E76969C, (0x7E76946E, 0x7E76947A), None),
         ("pinhole1", (73, 82), 0x7E7696AC, (0x7E7694CE, 0x7E7694DA), None), ("diorama", (86, 88), 0x7E7696B0, (0x7E7694E6, 0x7E7694F2), None),
         ("grainy", (102, 103), 0x7E7696BC, (0x7E76952E, 0x7E76953A), 104), ("sepia", (106,), 0x7E7696C0, (0x7E769546, 0x7E769552), 108),
         ("dramatic", (108,), 0x7E7696C4, (0x7E76955E, 0x7E76956A), 109), ("keyline", (145, 146), 0x7E7696B8, (0x7E769516, 0x7E769522), 119),
         ("watercolor", (167, 168), 0x7E7696EC, (0x7E769622, 0x7E76962E), 120)]
REMAP = {0x7E71BE39: (b"\x8a\x4a", b"\x8a\x66"), 0x7E71BE4B: (b"\x8a\x5b", b"\x8a\x6a"), 0x7E71BE50: (b"\x8a\x60", b"\x8a\x6c"),       # Grainy 74 -> 102, Sepia 91 -> 106, Dramatic 96 -> 108
         0x7E71BE7E: (b"\x2e\xa3\x00", b"\x2e\x91\x00"), 0x7E71BE8F: (b"\x2e\xb5\x00", b"\x2e\xa7\x00")}                              # Key Line 163 -> 145, Watercolor 181 -> 167
LOOK_SHARED, CHROMA_LINEAR, NO_MODULE = 0x7E56E94A, 0x7E5664A0, 0x7E72A665
def asm():
    L = ["# generated by build_slots12.py: generic film-slot helpers for nine slots (NOTES 33); linked at 0x7ECB0888", "        .text", "        .global gcommon, matrix12, recs, endc"]
    for i, (n, codes, *_r) in enumerate(SLOTS):
        L += [f"        .global g_{n}, t_{n}", f"g_{n}: mov tri_{n},a1          # {n}: codes {codes}"] + (["        bra gcommon"] if i < len(SLOTS) - 1 else [])
    L += ["gcommon: extbu d2", "        movbu (28,sp),d3", "        mov d2,d0", "        mov d3,d1", "        mov (a1),a0", "        call PICK,[d2,d3],8", "        mov a0,(a2)",
          "        mov d2,d0", "        mov d3,d1", "        mov (4,a1),a0", "        call PICK,[d2,d3],8", "        mov a0,(a3)", "        mov (8,a1),a0", "        jmp GTAIL"]
    hits = [("T1", (85, 87)), ("T2", (72, 81)), ("T3", (70, 79))] + [(f"t_{n}", c) for n, c, *_r in SLOTS]
    half = 7                                                         # two chains so that every beq stays within 8-bit range
    for part, (lab, hs, nxt) in enumerate((("matrix12", hits[:half], "chainB"), ("chainB", hits[half:], "M_NONE"))):
        L.append(f"{lab}:")
        for k, (t, cs) in enumerate(hs):
            for c in cs: L += [f"        cmp {c},d0", f"        beq h{part}_{k}"]
        L.append(f"        jmp {nxt}")
        for k, (t, cs) in enumerate(hs):
            L += [f"h{part}_{k}: mov {t},a1"] + ([f"        bra mt{part}"] if k < len(hs) - 1 else [])
        L += [f"mt{part}: mov d3,a0", "        jmp M_APPLY"]
    L += ["        .balign 4, 0xff", "endc:"]
    for n, *_r in SLOTS: L.append(f"t_{n}: .hword 256,0,0, 0,256,0, 0,0,256")
    L.append("        .balign 4, 0xff")
    for i, (n, *_r) in enumerate(SLOTS): L.append(f"tri_{n}: .long recs + {3 * i}*32, recs + {3 * i + 1}*32, recs + {3 * i + 2}*32")
    L.append("recs:")
    for i, (n, *_r) in enumerate(SLOTS):
        for ch in range(3):
            own = f"{POOL[3 * i + ch]:#x}"; L.append(f"        .long {DEF[0]:#x}, {own}, {DEF[2]:#x}, {own}, {DEF[4]:#x}, {own}, {DEF[6]:#x}, {own}")
    return "\n".join(L) + "\n"
def assemble():
    run = lambda *a: subprocess.run(a, check=True, capture_output=True, text=True, cwd=HERE).stdout
    open(os.path.join(HERE, "cave12.s"), "w").write(asm())
    run(BIN + "as", "-o", "cave1.o", os.path.join("..", "slot3", "cave.s"))
    ext1 = dict(PICK=0x7E56B732, GTAIL=0x7E56B852, M_T1=0x7E56C6B8, M_T2=0x7E56C6C3, M_APPLY=0x7E56C764, M_NONE=0x7E56C76B)
    run(BIN + "ld", "-Ttext=%#x" % CAVE1, "-e", "gamma3", *[f"--defsym={k}={v:#x}" for k, v in ext1.items()], "-o", "cave1.elf", "cave1.o")
    run(BIN + "objcopy", "-O", "binary", "-j", ".text", "cave1.elf", "cave1.bin")
    nm = lambda f: {l.split()[2]: int(l.split()[0], 16) for l in run(BIN + "nm", f).splitlines() if len(l.split()) == 3}
    s1 = nm("cave1.elf")
    ext2 = dict(PICK=0x7E56B732, GTAIL=0x7E56B852, M_APPLY=0x7E56C764, M_NONE=0x7E56C76B, T1=0x7E768F46, T2=0x7E768F58, T3=s1["t3"])
    run(BIN + "as", "-o", "cave12.o", "cave12.s")
    run(BIN + "ld", "-Ttext=%#x" % CAVE2, "-e", "gcommon", *[f"--defsym={k}={v:#x}" for k, v in ext2.items()], "-o", "cave12.elf", "cave12.o")
    run(BIN + "objcopy", "-O", "binary", "-j", ".text", "cave12.elf", "cave12.bin")
    return open(os.path.join(HERE, "cave1.bin"), "rb").read(), s1, open(os.path.join(HERE, "cave12.bin"), "rb").read(), nm("cave12.elf")
def gamma_hash(s1, s2):
    T = 0x7E78C154; D = 0x7E56B861; ent = [list(struct.unpack_from("<II", b0, T - B + 8 * i)) for i in range(32)]
    def put(code, h):
        k = (code - 70) & 0xFFFFFFFF
        for e in ent:
            if e[0] == k: e[1] = h; return
        i = k & 31
        while ent[i][0] != 0: i = (i + 1) % 32
        ent[i] = [k, h]
    for e in ent:
        if e[0] in (77, 80) and e[1] == 0x7E56B7F0: e[1] = D             # codes 147, 150 (other Light Tone numbers): default
    put(72, 0x7E56B82A); put(81, 0x7E56B82A); put(79, s1["gamma3"])
    for n, codes, *_r in SLOTS:
        for c in codes: put(c, s2[f"g_{n}"])
    i = 0
    while ent[i][0] != 0: i += 1
    for e in ent:
        if e[0] == 0: e[1] = D
    ent[i][1] = s1["gamma3"]
    return T, ent, i
def main():
    c1, s1, c2, s2 = assemble()
    assert len(c2) <= CAVE2_LEN and b0[CAVE2 - B:CAVE2 - B + CAVE2_LEN] == b"\xff" * CAVE2_LEN and s2["recs"] % 4 == 0 and all(s2[f"t_{n}"] % 2 == 0 for n, *_r in SLOTS)
    assert len(set(POOL[:27])) == 27
    ops = [op(CAVE1, c1), op(CAVE2, c2), op(0x7E56C6A5, b"\xdc" + struct.pack("<i", s2["matrix12"] - 0x7E56C6A5)), op(0x7E56B7A7, b"\x45")]
    T, ent, i70 = gamma_hash(s1, s2)
    for i, (k, h) in enumerate(ent):
        if k != u32(T + 8 * i): ops.append(op(T + 8 * i, struct.pack("<I", k)))
        if h != u32(T + 8 * i + 4) and i not in (2, 11): ops.append(op(T + 8 * i + 4, struct.pack("<I", h)))
    for n, codes, *_r in SLOTS:
        for c in codes:
            ops.append(op(0x7E78C8E4 + 4 * (c - 8), struct.pack("<I", LOOK_SHARED))); ops.append(op(0x7E78AEA4 + 4 * (c - 69), struct.pack("<I", CHROMA_LINEAR)))
    ops += [op(0x7E768DB8, struct.pack("<10H", *[256] * 10)),                                       # all five WB multiplier pairs -> 1.0
            op(0x7E85C45C + 8 * 1 + 4, struct.pack("<I", NO_MODULE)), op(0x7E85C45C + 8 * 14 + 4, struct.pack("<I", NO_MODULE)),     # Pin Hole I, Diorama
            op(0x7E85C45C + 8 * 2 + 4, struct.pack("<I", NO_MODULE)), op(0x7E85C45C + 8 * 4 + 4, struct.pack("<I", NO_MODULE)),      # numbers 106, 108 (Pin Hole II / III modules)
            op(0x7E72A6F7, b"\xff"), op(0x7E72A739, b"\xff")]                                       # Soft Focus blur
    for a, (old, new) in REMAP.items():
        assert b0[a - B:a - B + len(old)] == old; ops.append(op(a, new))
    for r, tabs in zip(PRO_RECS, pro_tabs):                                                         # Pro 400H records: member 1 of every column = its stills table, member 0 = stock
        ops.append(op(r, struct.pack("<8I", DEF[0], tabs[1], DEF[2], tabs[1], DEF[4], tabs[1], DEF[6], tabs[1])))
    ops = [o for o in ops if o["expect"] != o["new"]]
    base = dict(base="firmware/stock/E-PM2/OLY_E_101_1600_0000_0000.BIN", base_sha256="34d339ac3986ba8c10f494dbe2e4ae8f143ebf5bbfaa356e3ff9b7f40fc3e300", status="built, NOT camera-tested")
    json.dump(dict(name="slots12-code", description="Twelve film slots (replaces slot3-code / slots7-code): code areas, gamma hash, look / chroma / effect dispatch, WB pairs, and the art_GetFilterType "
                   "immediates that send Grainy Film, Gentle Sepia, Dramatic Tone, Key Line, Watercolor to the numbers 102, 106, 108, 145, 167. NOTES §33.", ops=ops, **base),
              open(os.path.join(ROOT, "patches/slots12-code.json"), "w"), indent=1)
    dflt = b0[0x7E74E9BC - B:0x7E74E9BC - B + 512]; nops = []; lay = {}
    for i, (n, codes, sat, six, mode) in enumerate(SLOTS):
        tabs = POOL[3 * i:3 * i + 3]; lay[n] = dict(codes=codes, tabs=[hex(t) for t in tabs], sat=hex(sat), six=[hex(x) for x in six], matrix=hex(s2[f"t_{n}"]), stub=hex(s2[f"g_{n}"]))
        for t in tabs: nops.append({"type": "bytes", "block": 0, "offset": hex(t - B), "expect": b0[t - B:t - B + 512].hex(), "new": dflt.hex()})
        nops += [op(sat, struct.pack("<2H", 282, 282)), op(six[0], struct.pack("<6h", *[0] * 6)), op(six[1], struct.pack("<6h", *[0] * 6))]
    json.dump(dict(name="slots12-neutral", description="Stock Natural settings in the nine generic film slots (test content). NOTES §33.", ops=[o for o in nops if o["expect"] != o["new"]], **base),
              open(os.path.join(ROOT, "patches/slots12-neutral.json"), "w"), indent=1)
    pro = json.load(open(os.path.join(ROOT, "patches/film-pro400h-pa2.json"))); freed = {hex(t - B) for t in FREED}; n0 = len(pro["ops"])
    pro["ops"] = [o for o in pro["ops"] if o.get("offset") not in freed]; assert n0 - len(pro["ops"]) == 21
    pro["name"] += "-s12"; pro["description"] += " Reduced to its three stills tables: for builds with slots12-code."
    json.dump(pro, open(os.path.join(ROOT, "patches/film-pro400h-pa2-s12.json"), "w"), indent=1)
    json.dump(dict(slots=lay, s1={k: hex(v) for k, v in s1.items()}, s2={k: hex(v) for k, v in s2.items()}, hash=[[hex(k), hex(h)] for k, h in ent]), open(os.path.join(HERE, "slots12_layout.json"), "w"), indent=1)
    print("code area 2:", len(c2), "of", CAVE2_LEN, "B (code", s2["endc"] - CAVE2, "B); structural ops:", len(ops), "; code 70 matches hash entry", i70, "; free hash entries:", sum(1 for e in ent if e[0] == 0))
if __name__ == "__main__":
    main()
